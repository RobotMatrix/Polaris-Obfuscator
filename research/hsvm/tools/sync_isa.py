#!/usr/bin/env python3
"""Generate / verify the HSV ISA mirror header.

Source of truth : src/llvm/include/llvm/Transforms/Obfuscation/HSVMOpcodes.def
Generated mirror: research/hsvm/include/hsvm/isa.h

    sync_isa.py --write   # regenerate the mirror
    sync_isa.py --check   # fail if the mirror is stale (used by ctest)

The check is what keeps the research harness and the future compiler pass on
the same opcode numbering; drifting silently would make every trace ambiguous.
"""
import argparse
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
DEF_PATH = os.path.join(ROOT, "src", "llvm", "include", "llvm", "Transforms",
                        "Obfuscation", "HSVMOpcodes.def")
HEADER_PATH = os.path.join(HERE, "..", "include", "hsvm", "isa.h")

LINE_RE = re.compile(r"^HSV_OPCODE\(\s*([A-Za-z_][A-Za-z0-9_]*)\s*,\s*"
                     r"(0x[0-9A-Fa-f]+|\d+)\s*\)\s*$")


def parse_def(path):
    entries = []
    with open(path, "r", encoding="utf-8") as fh:
        for lineno, line in enumerate(fh, 1):
            line = line.strip()
            if not line or line.startswith("//"):
                continue
            m = LINE_RE.match(line)
            if not m:
                raise SystemExit("error: %s:%d: cannot parse: %s"
                                 % (path, lineno, line))
            name, value = m.group(1), int(m.group(2), 0)
            if not 0 <= value <= 0xFF:
                raise SystemExit("error: %s:%d: opcode value out of range"
                                 % (path, lineno))
            entries.append((name, value))
    if not entries:
        raise SystemExit("error: no HSV_OPCODE entries in %s" % path)
    values = [v for _, v in entries]
    if len(set(values)) != len(values):
        raise SystemExit("error: duplicate opcode values in %s" % path)
    names = [n for n, _ in entries]
    if len(set(names)) != len(names):
        raise SystemExit("error: duplicate opcode names in %s" % path)
    return entries


def render(entries):
    lines = []
    lines.append("//===- isa.h - HSV virtual ISA (GENERATED, DO NOT EDIT) ----*- C++ -*-===//")
    lines.append("//")
    lines.append("// Generated by research/hsvm/tools/sync_isa.py from")
    lines.append("// src/llvm/include/llvm/Transforms/Obfuscation/HSVMOpcodes.def")
    lines.append("//")
    lines.append("// Regenerate: python3 research/hsvm/tools/sync_isa.py --write")
    lines.append("// Verify    : python3 research/hsvm/tools/sync_isa.py --check")
    lines.append("//")
    lines.append("//===----------------------------------------------------------------------===//")
    lines.append("#ifndef HSV_M_ISA_H")
    lines.append("#define HSV_M_ISA_H")
    lines.append("")
    lines.append("#include <cstdint>")
    lines.append("")
    lines.append("namespace hsvm {")
    lines.append("")
    lines.append("enum class Opcode : uint8_t {")
    for name, value in entries:
        lines.append("  %s = 0x%02X," % (name, value))
    lines.append("};")
    lines.append("")
    lines.append("constexpr uint32_t kNumOpcodes = %d;" % len(entries))
    lines.append("constexpr uint32_t kInstrBytes = 8;")
    lines.append("")
    lines.append("inline const char *opcodeName(Opcode op) {")
    lines.append("  switch (op) {")
    for name, _ in entries:
        lines.append('  case Opcode::%s: return "%s";' % (name, name.lower()))
    lines.append("  }")
    lines.append('  return "?";')
    lines.append("}")
    lines.append("")
    lines.append("} // namespace hsvm")
    lines.append("")
    lines.append("#endif // HSV_M_ISA_H")
    lines.append("")
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    group = ap.add_mutually_exclusive_group(required=True)
    group.add_argument("--write", action="store_true",
                       help="regenerate the mirror header")
    group.add_argument("--check", action="store_true",
                       help="fail when the mirror is stale")
    args = ap.parse_args()

    entries = parse_def(DEF_PATH)
    expected = render(entries)

    if args.write:
        with open(HEADER_PATH, "w", encoding="utf-8") as fh:
            fh.write(expected)
        print("wrote %s (%d opcodes)" % (os.path.relpath(HEADER_PATH, ROOT),
                                         len(entries)))
        return 0

    try:
        with open(HEADER_PATH, "r", encoding="utf-8") as fh:
            actual = fh.read()
    except OSError:
        print("error: missing mirror header %s; run --write" % HEADER_PATH,
              file=sys.stderr)
        return 1

    if actual != expected:
        print("error: %s is stale; run sync_isa.py --write"
              % os.path.relpath(HEADER_PATH, ROOT), file=sys.stderr)
        return 1

    print("isa mirror: ok (%d opcodes)" % len(entries))
    return 0


if __name__ == "__main__":
    sys.exit(main())
