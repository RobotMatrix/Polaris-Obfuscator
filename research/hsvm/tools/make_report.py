#!/usr/bin/env python3
"""Compose a gate report (run.json) from attack outputs.

Every number in the report comes from a file produced by a script; this tool
only binds them to the commit, the protocol hash and the parameter hash, then
runs the validator. Refusing to hand-write metrics is the point.

    make_report.py --gate G0 --run-id g0-linear-12345 --out reports/G0/run.json \
        --metrics a1=reports/G0/a1.json --metrics a2=reports/G0/a2.json \
        --raw-log trace.jsonl --queries 16 --censored=false \
        --params-hash 0123456789abcdef \
        --evidence attacks/a1_trace_diff.py
"""

import argparse
import datetime
import json
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
CHECKER = os.path.join(HERE, "check_protocol.py")
VALIDATOR = os.path.join(HERE, "report.py")


def git_commit():
    try:
        out = subprocess.run(["git", "-C", ROOT, "rev-parse", "HEAD"],
                             capture_output=True, text=True, check=True)
        return out.stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


def protocol_hash(path):
    res = subprocess.run([sys.executable, CHECKER, path, "--quiet"],
                         capture_output=True, text=True)
    if res.returncode != 0:
        raise SystemExit("protocol check failed:\n" + res.stderr)
    m = re.search(r"protocol_sha256=([0-9a-f]{64})", res.stdout)
    if not m:
        raise SystemExit("protocol checker did not print a hash")
    return m.group(1)


def flatten(prefix, path):
    with open(path, "r", encoding="utf-8") as fh:
        doc = json.load(fh)
    if not isinstance(doc, dict):
        raise SystemExit("%s: expected a JSON object" % path)
    out = {}
    for key, value in doc.items():
        if isinstance(value, bool):
            value = 1.0 if value else 0.0
        if isinstance(value, (int, float)):
            out["%s_%s" % (prefix, key)] = float(value)
    if not out:
        raise SystemExit("%s: no scalar metrics found" % path)
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--gate", required=True)
    ap.add_argument("--run-id", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--metrics", action="append", default=[],
                    metavar="NAME=PATH")
    ap.add_argument("--raw-log", required=True)
    ap.add_argument("--queries", type=int, required=True)
    ap.add_argument("--censored", choices=["true", "false"], required=True)
    ap.add_argument("--budget", type=int, default=None)
    ap.add_argument("--params-hash", required=True)
    ap.add_argument("--protocol", default=os.path.join(HERE, "..", "protocol.json"))
    ap.add_argument("--evidence", action="append", default=[])
    args = ap.parse_args()

    metrics = {}
    for spec in args.metrics:
        if "=" not in spec:
            raise SystemExit("--metrics expects NAME=PATH, got %r" % spec)
        name, path = spec.split("=", 1)
        metrics.update(flatten(name, path))

    report = {
        "run_id": args.run_id,
        "gate": args.gate,
        "created_at": datetime.datetime.now(datetime.timezone.utc)
        .strftime("%Y-%m-%dT%H:%M:%SZ"),
        "git_commit": git_commit(),
        "params_hash": args.params_hash,
        "protocol_sha256": protocol_hash(args.protocol),
        "attacker_model": "A2",
        "seeds": [12345],
        "metrics": metrics,
        "queries_used": args.queries,
        "censored": args.censored == "true",
        "raw_log": args.raw_log,
        "evidence": args.evidence or ["generated by tools/make_report.py"],
    }
    if args.budget is not None:
        report["budget"] = args.budget

    os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
    with open(args.out, "w", encoding="utf-8") as fh:
        json.dump(report, fh, indent=2, sort_keys=True)
        fh.write("\n")

    res = subprocess.run([sys.executable, VALIDATOR, "validate", args.out],
                         capture_output=True, text=True)
    sys.stdout.write(res.stdout)
    sys.stderr.write(res.stderr)
    return res.returncode


if __name__ == "__main__":
    sys.exit(main())
