// FNV-1a
static inline uint32_t fnv1a(const uint8_t *p, size_t n) {
    uint32_t h = 0x811c9dc5;
    for (size_t i = 0; i < n; i++) h = (h ^ p[i]) * 0x01000193;
    return h;
}

static uint32_t g_key_tampered = 0;

// 分片完整性校验: 改写任一 part 字节 → 对应校验失败 → g_key_tampered 置位
static inline int verify_shards() {
    g_key_tampered &= 0x8000u;
#ifndef WBAES_DYNAMIC_KEY
    for (int s = 0; s < 4; s++) {
        uint8_t part[4];
        for (int b = 0; b < 4; b++)
            part[b] = KBLK_P(s)[KOFF[s] + b];
        uint32_t h = fnv1a(part, 4);
        uint32_t expect = 0;
        for (int b = 0; b < 4; b++)
            expect |= (uint32_t)CHBLK_P(s)[CHOFF[s] + b] << (8 * b);
        if (h != expect) g_key_tampered |= (1u << s);
    }
#endif
    return (g_key_tampered & 0x7FFF) == 0;
}

// 密钥字节重组: 跨块寄存器内逐字节 (无 16B 连续形态)
// WBAES_DYNAMIC_KEY 模式下由 .cpp 侧覆盖 (运行时注入的分片)
// P2: 混入设备绑定因子 — 表 = f(主分片 ⊕ devbind), 二进制静态无完整密钥,
//     换设备因子不同 → 表重建后密钥不同 (一台破解不可复制).
#ifndef WBAES_NO_DEVBIND
extern "C" {
int devbind_init(void);
uint8_t devbind_byte(int i);
}
static int g_devbind_failed = 0;
#endif
#ifndef WBAES_DYNAMIC_KEY
static inline uint8_t key_byte(int i) {
    uint8_t kb = (uint8_t)(KBLK_P(i >> 2)[KOFF[i >> 2] + (i & 3)] ^ CBLK_P(i >> 2)[COFF[i >> 2] + (i & 3)]);
#ifndef WBAES_NO_DEVBIND
    // devbind 失败 (Keychain 全挂) → 静默回退纯分片 (可用性优先); 正常路径恒混入
    if (!g_devbind_failed && devbind_init() == 0)
        kb ^= devbind_byte(i);
    else
        g_devbind_failed = 1;
#endif
    return kb;
}
#endif

